import assert from 'node:assert/strict';
import { cultureCatalog } from '../src/lib/culture/seed';
import { parisDiscovery, validateDiscovery, entitiesFor, neighbors, parseTrail, branchTrail, searchEntities, dailyStory, parisDate } from '../src/lib/culture/paris-discovery';
import { PARIS_KEY, parsePersonal, writePersonal, emptyPersonal, exportBackup, restoreBackup } from '../src/lib/culture/paris-personal';
import { SHELF_KEY } from '../src/lib/culture/shelf';
validateDiscovery(parisDiscovery,cultureCatalog);
const entities=entitiesFor(cultureCatalog);
const path=['work:before-sunset','place:shakespeare','person:james-baldwin','work:giovannis-room'];
assert.deepEqual(parseTrail(path.join(','),entities),path);
assert.deepEqual(branchTrail(path,1,'theme:literary-paris'),path.slice(0,2).concat('theme:literary-paris'));
assert.throws(()=>parseTrail('work:before-sunset,person:james-baldwin',entities));
assert.throws(()=>parseTrail('place:unknown',entities));
assert.throws(()=>parseTrail(Array(26).fill(path.slice(0,2)).flat().join(','),entities));
assert.ok(neighbors('place:shakespeare').some(n=>n.id==='person:james-baldwin'));
assert.equal(neighbors('work:before-sunset',{...parisDiscovery,connections:parisDiscovery.connections.map(c=>({...c,review:'pending'}))}).length,0);
assert.throws(()=>validateDiscovery({...parisDiscovery,connections:[{...parisDiscovery.connections.find(c=>c.basis==='source')!,sourceIds:[]}]},cultureCatalog));
assert.throws(()=>validateDiscovery({...parisDiscovery,entities:[...parisDiscovery.entities,parisDiscovery.entities[0]]},cultureCatalog));
assert.ok(searchEntities(entities,cultureCatalog,'Baldwin','work').some(e=>e.id==='work:giovannis-room'));
assert.equal(searchEntities(entities,cultureCatalog,'zzz').length,0);
assert.equal(searchEntities(entities,cultureCatalog,'','invalid').length,0);
assert.equal(parisDate(new Date('2026-10-12T22:30:00Z')),'2026-10-13');
assert.equal(dailyStory(new Date('2026-10-12T10:00:00Z')).id,dailyStory(new Date('2026-10-12T20:00:00Z')).id);
assert.notEqual(dailyStory(new Date('2026-10-12T10:00:00Z')).id,dailyStory(new Date('2026-10-13T10:00:00Z')).id);
const data=new Map<string,string>([['saved-trips','untouched'],[SHELF_KEY,JSON.stringify({schemaVersion:1,workIds:['before-sunset']})]]);
const storage={getItem:(k:string)=>data.get(k)??null,setItem:(k:string,v:string)=>{data.set(k,v);},removeItem:(k:string)=>{data.delete(k);}};
writePersonal(storage,d=>({...d,trails:[{id:'test',title:'My trail',path,at:'2026-10-12T10:00:00Z'}]}));
assert.equal(parsePersonal(storage.getItem(PARIS_KEY)).trails[0].path.length,4);
assert.equal(data.get('saved-trips'),'untouched');
assert.equal(JSON.parse(storage.getItem(SHELF_KEY)!).workIds[0],'before-sunset');
const backup=exportBackup(storage);writePersonal(storage,()=>emptyPersonal());restoreBackup(storage,backup);
assert.equal(parsePersonal(storage.getItem(PARIS_KEY)).trails.length,1);
storage.setItem(PARIS_KEY,'{broken');assert.throws(()=>writePersonal(storage,()=>emptyPersonal()));assert.equal(storage.getItem(PARIS_KEY),'{broken');assert.ok(exportBackup(storage).includes('{broken'));
assert.throws(()=>parsePersonal(JSON.stringify({...emptyPersonal(),activities:[{id:'work:before-sunset',status:'visited',at:'invalid'}]})));
assert.throws(()=>writePersonal({...storage,setItem:()=>{throw Error('Quota');}},()=>emptyPersonal()));
console.log('Paris discovery: evidence, search, trails, rotation, persistence, backup and preservation passed.');
// Concurrent writers, valid-data quota failures and partial restore rollback.
storage.setItem(PARIS_KEY,JSON.stringify(emptyPersonal()));
const original=storage.getItem(PARIS_KEY);
assert.throws(()=>writePersonal({...storage,setItem:()=>{throw Error('Quota');}},d=>({...d,saved:[{id:'place:shakespeare',at:'2026-10-12T10:00:00Z'}]})));
assert.equal(storage.getItem(PARIS_KEY),original);
let reads=0;
assert.throws(()=>writePersonal({...storage,getItem:k=>{const value=storage.getItem(k);return ++reads===2?'concurrent-change':value;}},d=>d));
let failOnce=true;
assert.throws(()=>restoreBackup({...storage,setItem:(k,v)=>{if(k===SHELF_KEY&&failOnce){failOnce=false;throw Error('Quota');}storage.setItem(k,v);}},backup));
assert.equal(storage.getItem(PARIS_KEY),original);
const removed=JSON.stringify({...emptyPersonal(),saved:[{id:'place:no-longer-present',at:'2026-10-12T10:00:00Z'}]});
assert.equal(parsePersonal(removed).saved[0].id,'place:no-longer-present');
assert.throws(()=>parsePersonal(JSON.stringify({...emptyPersonal(),activities:[{id:'person:james-baldwin',status:'visited',at:'2026-10-12T10:00:00Z'}]})));
assert.equal(data.get('saved-trips'),'untouched');
console.log('PASS concurrent-write detection, quota safety, rollback and unavailable-item retention');

const audioPath=['work:paris-playlist','work:florence-sur-les-champs-elysees','work:an-intro-to-jazz-in-paris','place:shakespeare'];
assert.deepEqual(parseTrail(audioPath.join(','),entities),audioPath);
assert.equal(neighbors('work:paris-playlist').length,8);
writePersonal(storage,d=>({...d,activities:[{id:'work:la-seine',status:'listened',at:'2026-10-12T12:00:00Z'}]}));
const audioBackup=exportBackup(storage);writePersonal(storage,()=>emptyPersonal());restoreBackup(storage,audioBackup);
assert.equal(parsePersonal(storage.getItem(PARIS_KEY)).activities[0].status,'listened');
writePersonal(storage,d=>({...d,activities:d.activities.filter(a=>a.id!=='work:la-seine')}));
assert.equal(parsePersonal(storage.getItem(PARIS_KEY)).activities.length,0);
assert.equal(data.get('saved-trips'),'untouched');
console.log('PASS audio trails, listened status, undo and complete backup round-trip');
