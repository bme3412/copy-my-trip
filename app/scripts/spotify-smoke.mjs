// Run with Node 22+: node --experimental-strip-types scripts/spotify-smoke.mjs
import assert from 'node:assert/strict';
const values = new Map();
globalThis.sessionStorage = {getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key)};
let assigned;
globalThis.location = {origin: 'https://copy-my-trip.com', assign: url => { assigned = new URL(url); }};
const moduleUrl = new URL('../src/lib/culture/spotify.ts', import.meta.url);
const api = await import(moduleUrl);
assert.equal(Object.keys(api.spotifyTracks).length, 8);
assert.equal(api.safeReturnPath('//evil.example'), '/discover/place/paris');
assert.equal(api.safeReturnPath('/discover/work/la-boheme'), '/discover/work/la-boheme');
await api.authorizeSpotify(['la-boheme'], 0, '/discover/work/la-boheme');
assert.equal(assigned.origin, 'https://accounts.spotify.com');
assert.equal(assigned.searchParams.get('code_challenge_method'), 'S256');
assert.equal(assigned.searchParams.get('redirect_uri'), 'https://copy-my-trip.com/discover/spotify/callback');
let calls = 0;
globalThis.fetch = async () => { calls++; throw Error('Must not exchange an unverified code'); };
await assert.rejects(api.finishSpotifyLogin('?code=fake&state=wrong'), /verified/);
assert.equal(calls, 0);
const valid = await import(`${moduleUrl}?valid`);
await valid.authorizeSpotify(['la-boheme'], 0, '/discover/work/la-boheme');
const state = assigned.searchParams.get('state');
globalThis.fetch = async (url, options) => {
  calls++;
  assert.equal(url, 'https://accounts.spotify.com/api/token');
  assert(options.body.get('code_verifier'));
  assert.equal(options.body.get('client_secret'), null);
  return new Response(JSON.stringify({access_token: 'test-access', refresh_token: 'test-refresh', expires_in: 3600}));
};
const results = await Promise.all([valid.finishSpotifyLogin(`?code=test&state=${state}`), valid.finishSpotifyLogin(`?code=test&state=${state}`)]);
assert.equal(calls, 1, 'StrictMode callback must exchange only once');
assert.deepEqual(results[0].ids, ['la-boheme']);
assert.equal(await valid.spotifyToken(), 'test-access');
globalThis.fetch = async (url, options) => {
  assert(url.includes('device_id=test-device'));
  assert.deepEqual(JSON.parse(options.body), {uris: [`spotify:track:${valid.spotifyTracks['la-boheme']}`], offset: {position: 0}});
  return new Response(null, {status: 204});
};
await valid.startSpotifyTracks('test-device', ['la-boheme'], 0);
await assert.rejects(valid.startSpotifyTracks('test-device', ['missing'], 0), /unavailable/);
globalThis.fetch = async () => new Response(null, {status: 403});
await assert.rejects(valid.startSpotifyTracks('test-device', ['la-boheme'], 0), /Premium/);
globalThis.fetch = async () => new Response(null, {status: 401});
await assert.rejects(valid.startSpotifyTracks('test-device', ['la-boheme'], 0), /reconnect/);
assert.equal(valid.hasSpotifySession(), false);
values.set('elsewhere.spotify.token.v1', JSON.stringify({access_token: 'expired', refresh_token: 'refresh', expires_at: 0}));
calls = 0;
globalThis.fetch = async (_url, options) => {
  calls++; assert.equal(options.body.get('grant_type'), 'refresh_token');
  return new Response(JSON.stringify({access_token: 'renewed', expires_in: 3600}));
};
assert.deepEqual(await Promise.all([valid.spotifyToken(), valid.spotifyToken()]), ['renewed', 'renewed']);
assert.equal(calls, 1, 'Concurrent SDK requests must share one refresh');
assert.equal(JSON.parse(values.get('elsewhere.spotify.token.v1')).refresh_token, 'refresh');
values.set('elsewhere.spotify.token.v1', JSON.stringify({access_token: 'expired', refresh_token: 'refresh', expires_at: 0}));
let finishRefresh;
globalThis.fetch = () => new Promise(resolve => { finishRefresh = resolve; });
const pendingRefresh = valid.spotifyToken();
valid.clearSpotifySession();
finishRefresh(new Response(JSON.stringify({access_token: 'late-token', refresh_token: 'late-refresh', expires_in: 3600})));
await assert.rejects(pendingRefresh, /disconnected/);
assert.equal(valid.hasSpotifySession(), false, 'Disconnect must not be undone by an in-flight refresh');
console.log('Spotify: PKCE, callback state, duplicate callback, refresh rotation, queue selection, and playback errors passed.');
